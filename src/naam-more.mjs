    shortLong: (s, lg) => `${s ? `ছোট ও ডাকতে সহজ নাম: ${s}।` : ''}${lg ? ` লম্বা ও ঐতিহ্যবাহী নাম: ${lg} — এগুলো থেকে আদরের ডাকনামও সহজে হয়।` : ''}`,
